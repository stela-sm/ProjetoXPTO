package org.example;

public class Calculadora {

    public static Double sum (Double a, Double b){
        return a+b;
    }
    public static Double sub (Double a, Double b){
        return a-b;
    }
    public static Double mult (Double a, Double b){
        return a*b;
    }
    public static Double div (Double a, Double b){
        return a/b;
    }
}
